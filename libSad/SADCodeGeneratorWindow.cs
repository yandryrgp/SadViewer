using System.Diagnostics;
using System.IO;
using System.Text;
using System.Windows;
using static Simpro.Sad;

public static class PieceCodeGenerator
{
    public static void Generate(DataBase db, string nameDB = "g")
    {
        var filepath = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.Desktop), $"SADPieces.{nameDB}.cs");

        StringBuilder sb = new StringBuilder();

        // No regenerar si ya existe
        if (File.Exists(filepath))
        {
            Console.WriteLine($"[SAD] El archivo ya existe: {filepath}");
            return;
        }


        sb.AppendLine("//------------------------------------------------------------------------------");
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// Archivo generado automáticamente por PieceCodeGenerator.");
        sb.AppendLine("// Cualquier modificación manual será sobrescrita.");
        sb.AppendLine("//------------------------------------------------------------------------------");
        sb.AppendLine();

        sb.AppendLine("using Simpro;");
        sb.AppendLine();

        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Acceso tipado a las piezas SAD.");
        sb.AppendLine("/// Archivo generado automáticamente.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class SADPieces");
        sb.AppendLine("{");

        foreach (var block in db.Blocks)
        {
            string blockName = "Block_" + Sanitize(block.Name);

            sb.AppendLine($"    public static class {blockName}");
            sb.AppendLine("    {");

            foreach (var piece in block.Pieces)
            {
                string pieceName = Sanitize(piece.Name);

                sb.AppendLine(
                    $"        public static Piece {pieceName} => " +
                    $"SADManager.Instance.db.Blocks.First(x => x.Name == \"{block.Name}\")" +
                    $".Pieces.First(x => x.Name == \"{piece.Name}\");");
            }

            sb.AppendLine("    }");
            sb.AppendLine();
        }

        sb.AppendLine("}");

        File.WriteAllText(filepath, sb.ToString(), Encoding.UTF8);

#if UNITY_EDITOR
        UnityEditor.AssetDatabase.Refresh();
#endif

        Console.WriteLine($"[SAD] Archivo generado: {filepath}");

        Process.Start("explorer.exe", $"\"{Environment.GetFolderPath(Environment.SpecialFolder.Desktop)}\"");


        MessageBox.Show($"[SAD] Archivo generado: {filepath}");


    }

    private static string Sanitize(string value)
    {
        value = value.Replace(" ", "_")
                     .Replace("-", "_")
                     .Replace(".", "_")
                     .Replace("/", "_")
                     .Replace("\\", "_");

        if (char.IsDigit(value[0]))
            value = "_" + value;

        return value;
    }
}